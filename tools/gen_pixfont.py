"""Modular One SMK-37: the pixel letters of the screen (as the FM-1's Modular One): Silkscreen (Jason Kottke, SIL OFL
1.1, assets/fonts/ui) at its design size, no anti-aliasing, ASCII 32..126; m1_draw.c draws them at 2x.
Out: per glyph its advance and 5 rows of up to 8 pixels (bit 7 = the left one).

  tools/gen_pixfont.py OUT.h"""
import sys
from pathlib import Path
from PIL import ImageFont

FONT = Path(__file__).resolve().parents[1] / "assets" / "fonts" / "ui" / "silkscreen-latin-400-normal.woff"


def main(out):
    f = ImageFont.truetype(str(FONT), 8)
    adv, rows = [], []
    for c in range(32, 127):
        ch = chr(c)
        a = int(round(f.getlength(ch)))
        g = [0] * 5
        if ch != " ":
            m = f.getmask(ch, mode="1")
            x0, y0, _, _ = f.getbbox(ch)
            w, h = m.size
            for y in range(h):
                for x in range(w):
                    if m.getpixel((x, y)):
                        yy, xx = y0 + y - 4, x0 + x
                        if 0 <= yy < 5 and 0 <= xx < 8:
                            g[yy] |= 0x80 >> xx
        adv.append(max(a, 2))
        rows.append(g)
    with open(out, "w") as o:
        o.write("/* generated by tools/gen_pixfont.py: Silkscreen 8 px (SIL OFL 1.1), ASCII 32..126 */\n")
        o.write("static const uint8_t PF_ADV[95] = {%s};\n" % ", ".join(map(str, adv)))
        o.write("static const uint8_t PF_ROWS[95][5] = {\n")
        for g in rows:
            o.write("    {%s},\n" % ", ".join("0x%02X" % v for v in g))
        o.write("};\n")
    print(f"pixfont: {out}")


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "build/gen/m1_pixfont.h")
